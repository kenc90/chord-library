function createLanguageSelector() {
    const button = document.createElement('button');
    button.className = 'language-button';
    button.type = 'button';
    button.setAttribute('aria-label', t('language'));
    button.setAttribute('data-i18n-title', 'language');
    button.innerHTML = `
        <svg viewBox="0 0 24 24" width="20" height="20" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">
            <circle cx="12" cy="12" r="10"/>
            <path d="M2 12h20"/>
            <path d="M12 2a15.3 15.3 0 0 1 4 10 15.3 15.3 0 0 1-4 10 15.3 15.3 0 0 1-4-10 15.3 15.3 0 0 1 4-10z"/>
        </svg>`;

    const modal = document.createElement('div');
    modal.className = 'language-modal';
    modal.hidden = true;
    modal.innerHTML = `
        <div class="language-modal-backdrop"></div>
        <div class="language-modal-dialog" role="dialog" aria-modal="true" aria-label="${t('language')}">
            <h2 class="language-modal-title" data-i18n="language">${t('language')}</h2>
            <div class="language-options">
                <button type="button" class="language-option" data-lang="en">English</button>
                <button type="button" class="language-option" data-lang="zh-Hant">繁體中文</button>
                <button type="button" class="language-option" data-lang="zh-Hans">简体中文</button>
            </div>
            <button type="button" class="language-modal-close" data-i18n="close">${t('close')}</button>
        </div>`;

    const options = modal.querySelectorAll('.language-option');
    const open = () => {
        options.forEach(option => option.classList.toggle('selected', option.dataset.lang === getLanguage()));
        modal.hidden = false;
    };
    const close = () => { modal.hidden = true; };

    button.addEventListener('click', open);
    modal.querySelector('.language-modal-backdrop').addEventListener('click', close);
    modal.querySelector('.language-modal-close').addEventListener('click', close);
    document.addEventListener('keydown', event => {
        if (event.key === 'Escape' && !modal.hidden) close();
    });
    options.forEach(option => option.addEventListener('click', () => {
        localStorage.setItem(LANGUAGE_STORAGE_KEY, option.dataset.lang);
        applyTranslations();
        applyTheme();
        document.dispatchEvent(new Event('languagechange'));
        close();
    }));

    getTopControls().appendChild(button);
    document.body.appendChild(modal);
}

function createMobileNav() {
    const nav = document.querySelector('.main-nav');
    if (!nav) return;

    const links = [...nav.querySelectorAll('.nav-link')].map(link => ({
        href: link.getAttribute('href'),
        label: link.textContent.trim(),
        i18nKey: link.dataset.i18n,
        active: link.classList.contains('active')
    }));

    const button = document.createElement('button');
    button.className = 'mobile-nav-button';
    button.type = 'button';
    button.setAttribute('aria-label', t('menu'));
    button.innerHTML = `
        <svg viewBox="0 0 24 24" width="20" height="20" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" aria-hidden="true">
            <line x1="4" y1="6" x2="20" y2="6"/>
            <line x1="4" y1="12" x2="20" y2="12"/>
            <line x1="4" y1="18" x2="20" y2="18"/>
        </svg>`;

    const modal = document.createElement('div');
    modal.className = 'mobile-nav-modal';
    modal.hidden = true;
    modal.innerHTML = `
        <div class="mobile-nav-backdrop"></div>
        <div class="mobile-nav-dialog" role="dialog" aria-modal="true" aria-label="${t('menu')}">
            <h2 class="mobile-nav-title" data-i18n="menu">${t('menu')}</h2>
            <div class="mobile-nav-links">
                ${links.map(link => `<a class="mobile-nav-link${link.active ? ' active' : ''}" href="${link.href}"${link.i18nKey ? ` data-i18n="${link.i18nKey}"` : ''}>${link.label}</a>`).join('')}
            </div>
            <button type="button" class="mobile-nav-close" data-i18n="close">${t('close')}</button>
        </div>`;

    const open = () => { modal.hidden = false; };
    const close = () => { modal.hidden = true; };

    button.addEventListener('click', open);
    modal.querySelector('.mobile-nav-backdrop').addEventListener('click', close);
    modal.querySelector('.mobile-nav-close').addEventListener('click', close);
    document.addEventListener('keydown', event => {
        if (event.key === 'Escape' && !modal.hidden) close();
    });

    document.body.appendChild(button);
    document.body.appendChild(modal);
}

document.addEventListener('DOMContentLoaded', () => {
    applyTranslations();
    createThemeToggle();
    createLanguageSelector();
    createMobileNav();
    applyTheme();
});
