function getLanguage() {
    return localStorage.getItem(LANGUAGE_STORAGE_KEY) || 'en';
}

// Dark is the default palette; light mode only applies once the user switches to it.
function getTheme() {
    return localStorage.getItem(THEME_STORAGE_KEY) === 'light' ? 'light' : 'dark';
}

function applyTheme() {
    const theme = getTheme();
    document.documentElement.dataset.theme = theme;
    const button = document.querySelector('.theme-button');
    if (!button) return;
    // The button announces the theme it switches to, matching the icon shown by style.css.
    const label = t(theme === 'light' ? 'darkMode' : 'lightMode');
    button.title = label;
    button.setAttribute('aria-label', label);
}

function getTopControls() {
    const existing = document.querySelector('.top-controls');
    if (existing) return existing;
    const controls = document.createElement('div');
    controls.className = 'top-controls';
    document.body.appendChild(controls);
    return controls;
}

function t(key) {
    const language = getLanguage();
    return TRANSLATIONS[language]?.[key] || TRANSLATIONS.en[key] || key;
}

function applyTranslations() {
    const language = getLanguage();
    document.documentElement.lang = language;
    document.querySelectorAll('[data-i18n]').forEach(element => {
        element.textContent = t(element.dataset.i18n);
    });
    document.querySelectorAll('[data-i18n-title]').forEach(element => {
        element.title = t(element.dataset.i18nTitle);
        element.setAttribute('aria-label', t(element.dataset.i18nTitle));
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
        element.placeholder = t(element.dataset.i18nPlaceholder);
        element.dataset.placeholder = t(element.dataset.i18nPlaceholder);
    });
    document.querySelectorAll('[data-drop-hint]').forEach(element => {
        element.dataset.dropHint = t('dropJsonHere');
    });
}

